import assert from 'assert';
import { spawnSync } from 'child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'fs';
import { tmpdir } from 'os';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

// Every install, in the image builds and the pull request checks, takes its packages from
// yarn.lock. Yarn's --frozen-lockfile still installs a package that a workspace asks for and
// yarn.lock does not list, so scripts/check-lockfile.mjs checks yarn.lock before each install. This
// test is in scbl-lib/test because every image build runs scbl-lib's tests, as the pull request
// checks do. It checks the repository's own yarn.lock, runs the script on made-up repositories in a
// temporary folder, and checks made-up Dockerfiles and the Dockerfiles that are here.
const repository = fileURLToPath(new URL('../../', import.meta.url));
const script = join(repository, 'scripts', 'check-lockfile.mjs');

function check(folder, args = []) {
  const result = spawnSync(process.execPath, [script, ...args], {
    cwd: folder,
    encoding: 'utf8',
    timeout: 60000
  });
  return { status: result.status, output: result.stdout + result.stderr };
}

// The repository's yarn.lock matches its package.json files. An image build has only some of the
// workspaces, and checks those.
let result = check(repository);
assert.strictEqual(result.status, 0, result.output);
assert.match(result.output, /^yarn\.lock matches the \d+ package\.json files here/);

// A made-up repository: three workspaces, one of which asks for another, and a yarn.lock exactly as
// Yarn writes it, with an entry shared by two ranges and a range with spaces in it.
const checksum = (letter) => `sha512-${letter.repeat(86)}==`;
const registry = 'https://registry.yarnpkg.com';
const lockfile = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@scope/a@^1.0.0", "@scope/a@^1.1.0":
  version "1.2.0"
  resolved "${registry}/@scope/a/-/a-1.2.0.tgz#1111"
  integrity ${checksum('a')}
  dependencies:
    b "^2.0.0"

b@^2.0.0:
  version "2.0.1"
  resolved "${registry}/b/-/b-2.0.1.tgz#2222"
  integrity ${checksum('b')}
  optionalDependencies:
    c-native ">=3.0.0 <4"

"c-native@>=3.0.0 <4":
  version "3.0.2"
  resolved "${registry}/c-native/-/c-native-3.0.2.tgz#3333"
  integrity ${checksum('c')}

d@^4.0.0:
  version "4.1.0"
  resolved "${registry}/d/-/d-4.1.0.tgz#4444"
  integrity ${checksum('d')}
`;
const files = {
  'package.json': {
    private: true,
    workspaces: ['lib', 'app', 'other'],
    devDependencies: { '@scope/a': '^1.0.0' }
  },
  'lib/package.json': { name: 'lib', version: '1.0.0', dependencies: { '@scope/a': '^1.1.0' } },
  'app/package.json': {
    name: 'app',
    version: '1.0.0',
    dependencies: { lib: '1.0.0', b: '^2.0.0' }
  },
  'other/package.json': { name: 'other', version: '1.0.0', dependencies: { d: '^4.0.0' } },
  'yarn.lock': lockfile
};

const folder = mkdtempSync(join(tmpdir(), 'check-lockfile-'));

// Checks the made-up repository with some of its files changed, or left out where they are null,
// from its root or another folder, with the arguments given.
function checkWith(changes = {}, { from = '.', args = [] } = {}) {
  rmSync(folder, { recursive: true, force: true });
  for (const [file, content] of Object.entries({ ...files, ...changes })) {
    if (content === null) continue;
    mkdirSync(dirname(join(folder, file)), { recursive: true });
    writeFileSync(
      join(folder, file),
      typeof content === 'string' ? content : JSON.stringify(content, null, 2)
    );
  }
  return check(join(folder, from), args);
}

// Fails, with a line that says why.
function refuses(changes, why, options) {
  const result = checkWith(changes, options);
  assert.strictEqual(result.status, 1, result.output);
  assert.ok(result.output.includes(why), `Expected "${why}" in:\n${result.output}`);
}

// Passes, having checked every workspace.
function passes(changes, options) {
  const result = checkWith(changes, options);
  assert.strictEqual(result.status, 0, result.output);
  assert.match(result.output, /package versions they need, and nothing else,/);
}

const withApp = (dependencies) => ({
  'app/package.json': { ...files['app/package.json'], dependencies }
});
const withRoot = (changes) => ({ 'package.json': { ...files['package.json'], ...changes } });
const replacing = (text, replacement) => ({ 'yarn.lock': lockfile.replace(text, replacement) });
const imageOnly = { 'other/package.json': null };

try {
  // It passes, and a workspace another one asks for needs no entry.
  result = checkWith();
  assert.strictEqual(result.status, 0, result.output);
  assert.match(result.output, /lists the 4 package versions they need, and nothing else,/);

  // An image without one of the workspaces passes too: yarn.lock may list that one's packages, and
  // the output says which workspace was not checked.
  result = checkWith(imageOnly);
  assert.strictEqual(result.status, 0, result.output);
  assert.match(result.output, /the 3 package\.json files here: it lists the 3 package versions/);
  assert.match(result.output, /The packages of other, which are not here, are not checked\./);
  assert.doesNotMatch(result.output, /nothing else/);

  // --all-workspaces, which the pull request checks pass, fails it when a workspace is missing.
  passes({}, { args: ['--all-workspaces'] });
  refuses(
    imageOnly,
    'Found no package.json in other, which package.json lists as workspaces. With ' +
      '--all-workspaces, every workspace must be here.',
    { args: ['--all-workspaces'] }
  );
  refuses({}, "Unknown option '--all-workspace'", { args: ['--all-workspace'] });

  // Yarn also takes the workspaces as the packages of an object, which are checked the same way.
  passes(withRoot({ workspaces: { packages: ['lib', 'app', './other'] } }));
  refuses(
    {
      ...withRoot({ workspaces: { packages: ['lib', 'app', 'other'] } }),
      ...withApp({ lib: '1.0.0', b: '^2.0.0', e: '^5.0.0' })
    },
    'app/package.json asks for e ^5.0.0, which yarn.lock does not list.'
  );
  // A workspace given as a wildcard, or outside the repository, fails it rather than being left
  // out, as do workspaces in a form Yarn does not take.
  refuses(
    withRoot({ workspaces: ['lib', 'ap*', 'other'] }),
    'package.json lists the workspaces as "ap*", which this check cannot follow. List each ' +
      'workspace by its folder in the repository, without wildcards,'
  );
  refuses(
    withRoot({ workspaces: { packages: ['lib', 'app', '{other}', '../other'] } }),
    'package.json lists the workspaces as "{other}", "../other", which'
  );
  refuses(
    withRoot({ workspaces: { packages: 'lib' } }),
    'package.json lists the workspaces as "lib", which'
  );

  // A workspace that asks for a package, or a range, that yarn.lock does not list fails it, as does
  // the root. So does a workspace in an image that has only some of them.
  const missing = 'app/package.json asks for e ^5.0.0, which yarn.lock does not list.';
  refuses(withApp({ lib: '1.0.0', b: '^2.0.0', e: '^5.0.0' }), missing);
  refuses({ ...imageOnly, ...withApp({ lib: '1.0.0', b: '^2.0.0', e: '^5.0.0' }) }, missing);
  refuses(
    {
      'lib/package.json': { name: 'lib', version: '1.0.0', dependencies: { '@scope/a': '^1.2.0' } }
    },
    'lib/package.json asks for @scope/a ^1.2.0, which yarn.lock does not list.'
  );
  refuses(
    withRoot({ devDependencies: { f: '^6.0.0' } }),
    'package.json asks for f ^6.0.0, which yarn.lock does not list.'
  );

  // Yarn installs a workspace that another one asks for from its folder only when the workspace's
  // version is inside the range asked for, and otherwise takes that name from the registry. So a
  // range the workspace's version is outside fails it, in an image too, as does a workspace with no
  // version.
  passes(withApp({ lib: '^1.0.0', b: '^2.0.0' }));
  const elsewhere =
    'app/package.json asks for lib 1.0.1, but the lib workspace is 1.0.0, so Yarn would take lib ' +
    'from the registry.';
  refuses(withApp({ lib: '1.0.1', b: '^2.0.0' }), elsewhere);
  refuses({ ...imageOnly, ...withApp({ lib: '1.0.1', b: '^2.0.0' }) }, elsewhere);
  refuses(
    { 'lib/package.json': { name: 'lib', dependencies: { '@scope/a': '^1.1.0' } } },
    'app/package.json asks for lib 1.0.0, but the lib workspace is not versioned, so Yarn would ' +
      'take lib from the registry.'
  );

  // So does a missing yarn.lock, which Yarn would install without.
  refuses({ 'yarn.lock': null }, 'Found no yarn.lock.');

  // And a package that needs one yarn.lock does not list.
  refuses(
    replacing(/"c-native@[\s\S]*?\n\n(?=d@)/, ''),
    'b@^2.0.0 needs c-native >=3.0.0 <4, which yarn.lock does not list.'
  );

  // Yarn installs the version a resolution in the root package.json asks for, whatever yarn.lock
  // lists, and writes that version under the resolution's own range. A resolution passes when every
  // entry for the package is that version, including through **/, and the resolution's own range
  // counts as needed.
  passes(withRoot({ resolutions: { '**/b': '^2.0.0' } }));
  const resolved = replacing('b@^2.0.0:', 'b@2.0.1, b@^2.0.0:');
  passes({ ...resolved, ...withRoot({ resolutions: { b: '2.0.1' } }) });
  // It fails when yarn.lock does not list the resolution, as before yarn install has been run.
  refuses(
    withRoot({ resolutions: { b: '2.0.0' } }),
    "package.json's resolutions ask for b 2.0.0, which yarn.lock does not list."
  );
  // Or when another entry for the package is another version.
  const older = [
    'b@2.0.0:',
    '  version "2.0.0"',
    `  resolved "${registry}/b/-/b-2.0.0.tgz#5555"`,
    `  integrity ${checksum('e')}`,
    '',
    'b@^2.0.0:'
  ].join('\n');
  refuses(
    { ...replacing('b@^2.0.0:', older), ...withRoot({ resolutions: { b: '2.0.0' } }) },
    "yarn.lock lists b@^2.0.0 at 2.0.1, but package.json's resolutions make Yarn install b 2.0.0."
  );
  // A resolution under one parent only cannot be compared with yarn.lock, so it fails.
  refuses(
    { ...resolved, ...withRoot({ resolutions: { 'app/b': '2.0.1' } }) },
    `package.json's resolutions name app/b. Name only the package, as in "ms" or "**/ms",`
  );

  // Yarn ignores an entry for a range its version is outside, and installs the newest version in
  // that range from the registry instead, so that fails it. These ranges and versions are read the
  // way Yarn's copy of semver reads them, prereleases included. A tag such as latest, which Yarn
  // takes as written, is not compared.
  const named = (index) => `e${String(index).padStart(2, '0')}`;
  const withRanges = (pairs) => ({
    'other/package.json': {
      ...files['other/package.json'],
      dependencies: {
        d: '^4.0.0',
        ...Object.fromEntries(pairs.map(([range], i) => [named(i), range]))
      }
    },
    'yarn.lock': [
      lockfile,
      ...pairs.map(([range, version], i) =>
        [
          `${/\s/.test(range) ? JSON.stringify(`${named(i)}@${range}`) : `${named(i)}@${range}`}:`,
          `  version "${version}"`,
          `  resolved "${registry}/${named(i)}/-/${named(i)}-${version}.tgz#5555"`,
          `  integrity ${checksum('e')}`,
          ''
        ].join('\n')
      )
    ].join('\n')
  });
  passes(
    withRanges([
      ['^2.4.1', '2.9.0'],
      ['^0.2.3', '0.2.9'],
      ['^0.0.3', '0.0.3'],
      ['~3.1.2', '3.1.9'],
      ['2.0.1', '2.0.1'],
      ['=0.155.0', '0.155.0'],
      ['1.x.x', '1.9.9'],
      ['^4', '4.5.0'],
      ['6', '6.1.0'],
      ['*', '5.0.0'],
      ['>= 2.1.2 < 3', '2.9.9'],
      ['>=0.6.2 <2.0.0', '1.0.0'],
      ['^3.0.0 || ^4.0.0', '4.1.0'],
      ['^1.0.0-beta.2', '1.0.0-beta.10'],
      ['^1.0.0-beta.2', '1.2.0'],
      ['1.2.3 - 2.3', '2.3.9'],
      ['<=1.2', '1.2.9'],
      ['>1.2', '1.3.0'],
      ['latest', '5.0.0']
    ])
  );
  const outside = [
    ['^2.4.1', '2.4.0'],
    ['^2.4.1', '3.0.0'],
    ['^0.2.3', '0.3.0'],
    ['^0.0.3', '0.0.4'],
    ['~3.1.2', '3.2.0'],
    ['2.0.1', '2.0.2'],
    ['1.x.x', '2.0.0'],
    ['*', '5.0.0-beta.1'],
    ['>= 2.1.2 < 3', '3.0.0'],
    ['^3.0.0 || ^4.0.0', '5.0.0'],
    ['^1.0.0-beta.2', '1.0.0-beta.1'],
    ['^1.0.0-beta.2', '1.0.1-beta.3'],
    ['^2.0.0', '2.1.0-beta.1'],
    ['1.2.3 - 2.3', '2.4.0'],
    ['<=1.2', '1.3.0'],
    ['>1.2', '1.2.9']
  ];
  result = checkWith(withRanges(outside));
  assert.strictEqual(result.status, 1, result.output);
  assert.deepStrictEqual(
    result.output.match(/^yarn\.lock lists .* which is outside that range, .*$/gm),
    outside.map(
      ([range, version], i) =>
        `yarn.lock lists ${named(i)}@${range} at ${version}, which is outside that range, so ` +
        'Yarn would ignore the entry and resolve the range afresh.'
    )
  );
  // A range that starts the way a version range does, but that cannot be read, fails it rather
  // than go unchecked.
  refuses(
    withRanges([['^1.2.3.4', '1.2.3']]),
    'yarn.lock lists e00@^1.2.3.4, but this check cannot read that range, so it cannot tell ' +
      'whether Yarn installs 1.2.3 for it.'
  );

  // A resolution makes Yarn install its version for the package's other ranges, so yarn install
  // writes it under them even when it is outside them, and that passes. The resolution's own range
  // is still compared.
  const bAt = (header, version) => ({
    'yarn.lock': lockfile
      .replace('b@^2.0.0:', header)
      .replace('version "2.0.1"', `version "${version}"`)
      .replace('b-2.0.1.tgz', `b-${version}.tgz`)
  });
  passes({ ...bAt('b@1.9.0, b@^2.0.0:', '1.9.0'), ...withRoot({ resolutions: { b: '1.9.0' } }) });
  refuses(
    { ...bAt('b@^2.0.0, b@^2.0.1:', '2.0.0'), ...withRoot({ resolutions: { b: '^2.0.1' } }) },
    'yarn.lock lists b@^2.0.1 at 2.0.0, which is outside that range,'
  );

  // With every workspace here, a package that nothing needs any more fails it. Without one, that
  // package may be the missing workspace's, so it passes.
  const unused = [
    lockfile,
    'e@^5.0.0:',
    '  version "5.0.0"',
    `  resolved "${registry}/e/-/e-5.0.0.tgz#5555"`,
    `  integrity ${checksum('e')}`,
    ''
  ].join('\n');
  refuses({ 'yarn.lock': unused }, 'yarn.lock lists e@^5.0.0, which nothing here needs any more.');
  result = checkWith({ ...imageOnly, 'yarn.lock': unused });
  assert.strictEqual(result.status, 0, result.output);
  // A key without a range, which Yarn does not write, fails it, in an image too, where Yarn would
  // fetch it in place of the workspace. A key with an empty range is what Yarn writes for one.
  const bare = [
    lockfile,
    'lib:',
    '  version "1.0.0"',
    `  resolved "${registry}/lib/-/lib-1.0.0.tgz#6666"`,
    `  integrity ${checksum('f')}`,
    ''
  ].join('\n');
  for (const changes of [{}, imageOnly])
    refuses(
      { ...changes, 'yarn.lock': bare },
      'Line 29 of yarn.lock lists lib with no range, which Yarn does not write.'
    );
  passes({
    ...withApp({ lib: '1.0.0', b: '^2.0.0', e: '' }),
    'yarn.lock': unused.replace('e@^5.0.0:', 'e@:')
  });
  // So does a package that no other package needs any more.
  refuses(
    replacing('\n  optionalDependencies:\n    c-native ">=3.0.0 <4"', ''),
    'yarn.lock lists c-native@>=3.0.0 <4, which nothing here needs any more.'
  );

  // Every package comes from the npm registry over HTTPS, with a sha512 checksum.
  refuses(
    replacing(`${registry}/b/-/b-2.0.1.tgz`, 'https://example.com/b-2.0.1.tgz'),
    'yarn.lock fetches b@^2.0.0 from https://example.com/b-2.0.1.tgz#2222, ' +
      'not from the npm registry over HTTPS.'
  );
  refuses(
    replacing(`${registry}/b/`, 'http://registry.yarnpkg.com/b/'),
    'yarn.lock fetches b@^2.0.0 from http://registry.yarnpkg.com/b/-/b-2.0.1.tgz#2222, not from'
  );
  refuses(
    replacing(`\n  integrity ${checksum('d')}`, ''),
    'yarn.lock has no sha512 checksum for d@^4.0.0.'
  );
  refuses(
    replacing(checksum('d'), 'sha1-dddddddddddddddddddddddddds='),
    'yarn.lock has no sha512 checksum for d@^4.0.0.'
  );
  // The checksum is checked once for an entry shared by two ranges, and named by the first.
  result = checkWith(replacing(checksum('a'), 'sha1-aaaaaaaaaaaaaaaaaaaaaaaaaaa='));
  assert.strictEqual(result.status, 1, result.output);
  assert.deepStrictEqual(result.output.match(/no sha512 checksum for .*/g), [
    'no sha512 checksum for @scope/a@^1.0.0.'
  ]);

  // Each entry fetches the tarball of its own package and version, from the registry: not another
  // package's, another version's, or one at another path.
  refuses(
    replacing(`${registry}/b/-/b-2.0.1.tgz`, `${registry}/left-pad/-/left-pad-1.3.0.tgz`),
    `yarn.lock fetches b@^2.0.0 from ${registry}/left-pad/-/left-pad-1.3.0.tgz#2222, which is ` +
      'not b 2.0.1.'
  );
  refuses(replacing('b-2.0.1.tgz', 'b-2.0.0.tgz'), 'which is not b 2.0.1.');
  refuses(
    replacing('/b/-/b-2.0.1.tgz', '/b/-/../../c-native/-/b-2.0.1.tgz'),
    'which is not b 2.0.1.'
  );
  refuses(replacing('@scope/a/-/a-1.2.0', 'a/-/a-1.2.0'), 'which is not @scope/a 1.2.0.');
  // An alias installs the package after npm:, so it fetches that one's tarball.
  const alias = {
    'other/package.json': {
      ...files['other/package.json'],
      dependencies: { d: '^4.0.0', 'd-alias': 'npm:d@^4.1.0' }
    }
  };
  const aliased = (tarball) =>
    lockfile.replace(
      'd@^4.0.0:',
      [
        '"d-alias@npm:d@^4.1.0":',
        '  version "4.1.0"',
        `  resolved "${registry}/${tarball}#4444"`,
        `  integrity ${checksum('d')}`,
        '',
        'd@^4.0.0:'
      ].join('\n')
    );
  passes({ ...alias, 'yarn.lock': aliased('d/-/d-4.1.0.tgz') });
  refuses(
    { ...alias, 'yarn.lock': aliased('d-alias/-/d-alias-4.1.0.tgz') },
    'yarn.lock fetches d-alias@npm:d@^4.1.0 from'
  );

  // A yarn.lock that is not in Yarn's format, as after a merge conflict, fails it.
  refuses(
    replacing('b@^2.0.0:', '<<<<<<< HEAD\nb@^2.0.0:'),
    `Line 12 of yarn.lock is not in Yarn's format: "<<<<<<< HEAD"`
  );

  // So does any line Yarn would write another way, because Yarn reads some of them as other names,
  // or stops reading yarn.lock there. The line, and what Yarn writes there, are shown, with
  // characters outside printable ASCII escaped.
  for (const [header, shown] of [
    ['b@^2.0.0\tb@^2.0.0:', '"b@^2.0.0\\tb@^2.0.0:"'],
    ['b@^2.0.0\u00a0b@^2.0.0:', '"b@^2.0.0\\u00a0b@^2.0.0:"'],
    ['b@^2.0.0"b@^2.0.0":', '"b@^2.0.0\\"b@^2.0.0\\":"']
  ])
    refuses(
      replacing('b@^2.0.0:', header),
      `Line 12 of yarn.lock is ${shown}, but Yarn writes "b@^2.0.0:" there.`
    );
  refuses(
    replacing(`  resolved "${registry}/b/`, `# A note\n  resolved "${registry}/b/`),
    `Line 14 of yarn.lock is "# A note", but Yarn writes "  resolved \\"${registry}/b/`
  );
  refuses(
    replacing('    c-native ">', '    "c-native" ">'),
    `Line 17 of yarn.lock is "    \\"c-native\\" \\">=3.0.0 <4\\"", but Yarn writes ` +
      `"    c-native \\">=3.0.0 <4\\"" there.`
  );
  refuses(
    replacing('\n\nd@^4.0.0:', '\n\n\nd@^4.0.0:'),
    'Line 24 of yarn.lock is "", but Yarn writes "d@^4.0.0:" there.'
  );
  refuses({ 'yarn.lock': `${lockfile}\n` }, 'Line 29 of yarn.lock is "", but Yarn writes nothing');
  // A backslash, which Yarn can misread and no package name, version, address or checksum has,
  // fails it, as does an empty name, which Yarn cannot read back.
  refuses(
    replacing('  version "2.0.1"', '  version "2.0.\\u0031"'),
    `Line 13 of yarn.lock is not in Yarn's format: "  version \\"2.0.\\\\u0031\\""`
  );
  refuses(
    replacing('    b "^2.0.0"', '    "" "^2.0.0"'),
    `Line 10 of yarn.lock is not in Yarn's format: "    \\"\\" \\"^2.0.0\\""`
  );
  // So does a field Yarn writes only for packages from elsewhere, such as name, which makes it
  // install the entry under that name, or uid, or a block it does not write.
  refuses(
    replacing('  version "2.0.1"', '  name d\n  version "2.0.1"'),
    'Line 13 of yarn.lock is "  name d", a field Yarn does not write for a package from the npm ' +
      'registry.'
  );
  refuses(
    replacing('  version "2.0.1"\n', '  version "2.0.1"\n  uid "2.0.0"\n'),
    'Line 14 of yarn.lock is "  uid \\"2.0.0\\"", a field Yarn does not write'
  );
  refuses(
    replacing('  optionalDependencies:', '  peerDependencies:'),
    'Line 16 of yarn.lock is "  peerDependencies:", a field Yarn does not write'
  );
  // A package named like one of those fields is fine, and Yarn writes it first in a dependencies
  // block, as it orders an entry's fields.
  const uidEntry = [
    '',
    'uid@^1.0.0:',
    '  version "1.0.1"',
    `  resolved "${registry}/uid/-/uid-1.0.1.tgz#7777"`,
    `  integrity ${checksum('u')}`,
    ''
  ].join('\n');
  passes({
    'yarn.lock': lockfile.replace('    b "^2.0.0"', '    uid "^1.0.0"\n    b "^2.0.0"') + uidEntry
  });
  refuses(
    {
      'yarn.lock': lockfile.replace('    b "^2.0.0"', '    b "^2.0.0"\n    uid "^1.0.0"') + uidEntry
    },
    'Line 10 of yarn.lock is "    b \\"^2.0.0\\"", but Yarn writes "    uid \\"^1.0.0\\"" there.'
  );
  // Yarn keeps the line endings a yarn.lock has, so Windows ones pass.
  passes({ 'yarn.lock': lockfile.replace(/\n/g, '\r\n') });

  // Run from a folder without a package.json, it says where to run it.
  refuses(
    { 'docs/notes.txt': 'Notes' },
    'Found no package.json. Run this from the repository root.',
    { from: 'docs' }
  );
} finally {
  rmSync(folder, { recursive: true, force: true });
}

// A RUN's commands in JSON form, as one line, or as they are when they are not JSON.
function shellForm(commands) {
  try {
    return JSON.parse(commands).join(' ');
  } catch {
    return commands;
  }
}

// What is wrong with a Dockerfile: a stage that starts from neither a base image pinned by digest
// nor an earlier stage, a command that installs packages other than yarn install --frozen-lockfile
// after the yarn.lock check, or no install at all.
function dockerfileProblems(text) {
  const problems = [];
  const stages = [];
  let installs = 0;
  // The instructions, with their continued lines joined and the comments left out.
  const instructions = text
    .replace(/\\\r?\n/g, ' ')
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line !== '' && !line.startsWith('#'));
  for (const instruction of instructions) {
    const from = instruction.match(/^FROM\s+(?:--platform=\S+\s+)?(\S+)(?:\s+AS\s+(\S+))?/i);
    if (from) {
      if (!stages.includes(from[1]) && !/@sha256:[0-9a-f]{64}$/.test(from[1]))
        problems.push(`It builds from ${from[1]}, which is not pinned by digest.`);
      if (from[2]) stages.push(from[2]);
      continue;
    }
    // The shell commands of a RUN, in its shell or JSON form, or of a line of a RUN's
    // here-document, each after the operator that joins it to the one before. An install only
    // counts as checked when the check and every command between them are joined by &&.
    const commands = instruction.replace(/^RUN\s+(?:--\S+\s+)*/i, '');
    const parts = (commands.startsWith('[') ? shellForm(commands) : commands).split(
      /(&&|\|\||[;|&])/
    );
    let checked = false;
    for (let index = 0; index < parts.length; index += 2) {
      if (parts[index - 1] !== '&&') checked = false;
      const words = parts[index].trim().split(/\s+/);
      while (/^\w+=/.test(words[0])) words.shift();
      const [program = '', ...args] = words;
      const tool = program.split('/').pop();
      if (tool === 'node' && args[0] === 'scripts/check-lockfile.mjs') checked = true;
      // yarn on its own or with only options installs, as do its install and add commands, and
      // npm's.
      const installsPackages =
        (tool === 'yarn' &&
          (args.every((arg) => arg.startsWith('-')) ||
            args.some((arg) => ['install', 'add'].includes(arg)))) ||
        (tool === 'npm' && args.some((arg) => ['install', 'i', 'ci', 'add'].includes(arg)));
      if (!installsPackages) continue;
      installs++;
      const frozen =
        tool === 'yarn' && args.includes('install') && args.includes('--frozen-lockfile');
      if (!frozen || !checked)
        problems.push(
          `It installs packages with "${parts[index].trim()}", not with ` +
            'node scripts/check-lockfile.mjs && yarn install --frozen-lockfile.'
        );
    }
  }
  if (installs === 0) problems.push('It installs no packages.');
  return problems;
}

// A made-up Dockerfile, built the way the images are, passes, and each of these changes fails it.
const digest = (letter) => `@sha256:${letter.repeat(64)}`;
const dockerfile = `FROM dhi.io/node:26-dev${digest('a')} AS build
WORKDIR /opt/workdir/
COPY package.json yarn.lock ./
# Install from yarn.lock.
RUN node scripts/check-lockfile.mjs && \\
    yarn install --production --frozen-lockfile && \\
    yarn build-web-server
RUN node scripts/run-tests.mjs
FROM dhi.io/node:26${digest('b')}
COPY --from=build /opt/workdir /opt/workdir
CMD [ "node", "web-server/index.js" ]
`;
assert.deepStrictEqual(dockerfileProblems(dockerfile), []);
const install = 'node scripts/check-lockfile.mjs && yarn install --frozen-lockfile';
for (const [changed, problem] of [
  [dockerfile.replace(digest('a'), ''), 'It builds from dhi.io/node:26-dev, which is not'],
  [dockerfile.replace(digest('b'), ''), 'It builds from dhi.io/node:26, which is not'],
  [dockerfile.replace(' --frozen-lockfile', ''), 'with "yarn install --production", not with'],
  [
    dockerfile.replace('mjs && \\', 'mjs; \\'),
    'with "yarn install --production --frozen-lockfile"'
  ],
  [
    dockerfile.replace('mjs && \\', 'mjs || \\'),
    'with "yarn install --production --frozen-lockfile"'
  ],
  [
    dockerfile.replace('node scripts/check-lockfile.mjs && ', ''),
    'with "yarn install --production'
  ],
  [`${dockerfile}RUN yarn --production\n`, `with "yarn --production", not with ${install}.`],
  [`${dockerfile}RUN yarn\n`, 'It installs packages with "yarn", not with'],
  [`${dockerfile}RUN cd client && yarn add left-pad\n`, 'with "yarn add left-pad", not with'],
  [`${dockerfile}RUN npm install left-pad\n`, 'with "npm install left-pad", not with'],
  [`${dockerfile}RUN --mount=type=cache,target=/cache npm ci\n`, 'with "npm ci", not with'],
  [`${dockerfile}RUN ["yarn", "install"]\n`, 'with "yarn install", not with'],
  [`${dockerfile}RUN <<EOF\nyarn install --frozen-lockfile\nEOF\n`, 'with "yarn install --frozen'],
  [dockerfile.replace(/RUN node scripts\/check[\s\S]*?server\n/, ''), 'It installs no packages.']
]) {
  const problems = dockerfileProblems(changed);
  assert.ok(
    problems.some((line) => line.includes(problem)),
    `Expected "${problem}" in:\n${problems.join('\n')}\nfor:\n${changed}`
  );
}

// Each image's build stage checks yarn.lock before it installs, and installs with
// --frozen-lockfile, so Yarn installs only what yarn.lock lists. Each stage starts from a base
// image pinned by digest, which Dependabot proposes updates to, or from an earlier stage. An image
// build has only its own Dockerfile here; the pull request checks have all three.
const dockerfiles = ['web-server', 'ban-importer', 'discord-bot']
  .map((service) => `${service}/Dockerfile`)
  .filter((name) => existsSync(join(repository, name)));
assert.ok(dockerfiles.length > 0, 'Found no Dockerfile');
for (const name of dockerfiles) {
  const problems = dockerfileProblems(readFileSync(join(repository, name), 'utf8'));
  assert.deepStrictEqual(problems, [], `${name}:\n${problems.join('\n')}`);
}

